testthat::test_that("irregular domains and holes filter points", {
  outer <- rbind(c(0,0),c(4,0),c(4,4),c(0,4))
  hole <- rbind(c(1,1),c(2,1),c(2,2),c(1,2))
  d <- domain_exclusion(outer, list(hole))
  testthat::expect_equal(domain_contains(d, c(.5,1.5,5,NA), c(.5,1.5,5,0)), c(TRUE,FALSE,FALSE,NA))
  testthat::expect_true(domain_contains(d,0,0))
})
testthat::test_that("invalid geometry and CRS fail explicitly", {
  testthat::expect_error(domain_bbox(3,0,1,4))
  testthat::expect_error(domain_polygon(rbind(c(0,0),c(200,0),c(0,2))))
  testthat::expect_error(domain_validate(sf::st_sfc(sf::st_polygon(list(rbind(c(0,0),c(1,0),c(0,1),c(0,0)))))))
})
testthat::test_that("disjoint and dateline domains preserve coverage", {
  d <- domain_multipolygon(list(rbind(c(0,0),c(1,0),c(1,1),c(0,1)),rbind(c(3,0),c(4,0),c(4,1),c(3,1))))
  testthat::expect_equal(domain_contains(d,c(.5,2,3.5),c(.5,.5,.5)),c(TRUE,FALSE,TRUE))
  a <- domain_polygon(rbind(c(179,-1),c(-179,-1),c(-179,1),c(179,1)))
  testthat::expect_equal(domain_contains(a,c(179.5,-179.5,0),c(0,0,0)),c(TRUE,TRUE,FALSE))
  testthat::expect_equal(unname(domain_query_bbox(a)[c(1,3)]),c(-180,180))
})
testthat::test_that("circle, coastal buffer, region and import work", {
  d <- domain_circle(-90,0,10000)
  testthat::expect_equal(domain_contains(d,c(-90,-89),c(0,0)),c(TRUE,FALSE))
  line <- sf::st_sfc(sf::st_linestring(rbind(c(0,0),c(0,1))),crs=4326)
  b <- domain_coastal_buffer(line,10000)
  testthat::expect_true(domain_contains(b,0,.5))
  r <- sf::st_sf(id="a",geometry=d$geometry)
  testthat::expect_equal(domain_summary(domain_region(r,"id","a"))$features,1)
  f <- tempfile(fileext=".geojson")
  on.exit(unlink(f))
  domain_export(d,f)
  testthat::expect_true(domain_contains(domain_import(path=f),-90,0))
})
